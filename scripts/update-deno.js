/**
 * Syncs JSR metadata fields in deno.json from package.json.
 * Copies version, description, keywords, and license.
 * Also regenerates the public version constant in src/Version.ts.
 *
 * Usage:
 *   deno run -A scripts/update-deno.js   (or npm run up:deno)
 */

import { readFile, writeFile } from "node:fs/promises";

const FIELDS = ["version", "description", "keywords", "license"];

const pkg = JSON.parse(await readFile("package.json", "utf-8"));
const deno = JSON.parse(await readFile("deno.json", "utf-8"));

for (const field of FIELDS) {
  if (pkg[field] !== undefined) {
    deno[field] = pkg[field];
  }
}

await writeFile("deno.json", JSON.stringify(deno, null, 2) + "\n");
await writeFile(
  "src/Version.ts",
  `// Generated by tsdown.config.ts / scripts/update-deno.js — do not edit manually.
export const version = "${pkg.version}";
`,
);
console.log(`[update-deno] Synced JSR fields and src/Version.ts from package.json`);